package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// variant is one client family to resolve.
type variant struct {
	// name is the Go identifier suffix, e.g. "RE".
	name string
	// packetver is the PACKETVER date handed to the compiler.
	packetver int
	// zero selects upstream's RagexeZero client family, which upstream
	// tests with defined(PACKETVER_ZERO).
	zero bool
}

// writeTable emits the generated Go file holding the resolved client-to-server
// packet table for one variant.
//
// Two views are written: the resolved table keyed by opcode, and the
// registrations in upstream's own order. The ordered view matters because
// upstream re-binds the same parse handler to different opcodes across client
// versions, so "the opcode upstream registers this handler for" is only
// well defined against the registration order.
func writeTable(outDir string, src source, v variant, table []packetDef, ordered []packetDef) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/protocolgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", src.pkg)
	fmt.Fprintf(&b, "import \"github.com/bouroo/goAthena/pkg/ro/protocol/types\"\n\n")
	fmt.Fprintf(&b, "// %sPackets holds the resolved client-to-server packet table for the %s\n", v.name, v.name)
	fmt.Fprintf(&b, "// client family (PACKETVER %d), as the source itself resolves it: the two\n", v.packetver)
	fmt.Fprintf(&b, "// tables are registered in order and the last registration of an\n")
	fmt.Fprintf(&b, "// opcode wins.\n")
	fmt.Fprintf(&b, "var %sPackets = []types.Packet{\n", v.name)
	for _, d := range table {
		fmt.Fprintf(&b, "\t{Opcode: 0x%04x, Length: %d, Handler: %q, Name: %q, Offsets: []int{%s}},\n",
			d.opcode, d.length, d.handler, d.name, joinInts(d.offsets))
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// %sRegistrations holds the packets in the source's own registration order.\n", v.name)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// The source registers some handlers under several opcodes across client\n")
	fmt.Fprintf(&b, "// versions, so the last registration of a handler is the one the client\n")
	fmt.Fprintf(&b, "// uses at this PACKETVER.\n")
	fmt.Fprintf(&b, "var %sRegistrations = []types.Packet{\n", v.name)
	for _, d := range ordered {
		fmt.Fprintf(&b, "\t{Opcode: 0x%04x, Length: %d, Handler: %q, Name: %q, Offsets: []int{%s}},\n",
			d.opcode, d.length, d.handler, d.name, joinInts(d.offsets))
	}
	fmt.Fprintf(&b, "}\n")

	name := filepath.Join(outDir, fmt.Sprintf("packets_%s_gen.go", strings.ToLower(v.name)))
	if err := os.WriteFile(name, b.Bytes(), 0o600); err != nil {
		return fmt.Errorf("write file: %w", err)
	}
	return nil
}

// joinInts formats a slice of ints for Go source.
func joinInts(v []int) string {
	if len(v) == 0 {
		return ""
	}
	parts := make([]string, len(v))
	for i, n := range v {
		parts[i] = strconv.Itoa(n)
	}
	return strings.Join(parts, ", ")
}

// sortedOpcodes returns the resolved opcode constants of one variant, sorted
// by upstream symbol name.
func sortedOpcodes(ops map[string]int) []opcode {
	out := make([]opcode, 0, len(ops))
	for name, value := range ops {
		out = append(out, opcode{name: name, value: value})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}
